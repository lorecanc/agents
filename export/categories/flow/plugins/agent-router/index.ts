// agent-router: picks the model of each subagent from the provider the calling agent runs on.
//
// Scope: acts ONLY when a canonical archetype agent listed in routing.json (flow-build, flow-plan,
// ...) calls the `subagent` tool. Stamped bundles (hybrid-flow-*, *-pipeline-*) keep their fixed
// models, and every other agent is untouched. The decision rules live in ../../tools/_agent_router.js.
//
// How (V2 plugin API, verified against OpenCode 2.1.3)
//   model.request        remembers the agent and model of each session; the payload carries
//                        { sessionID, agent, model: { providerID, id, variant } }
//   tool.execute.before  on `subagent` calls, sets input.model ("provider/model#variant"). OpenCode
//                        picks a subagent's model as input.model ?? agent.model ?? parent model, and
//                        runs the tool with the input this hook leaves behind.
//
// routing.json sits next to this file and is generated by manage-agents
// (`manage-agents routing build`); changes apply to the next subagent call, no restart needed.
// Fail-open: a missing or broken routing.json, or any unexpected error, leaves the call as it is.
// Switches: OPENCODE_AGENT_ROUTER=off disables it; OPENCODE_AGENT_ROUTING=<path> reads another file.

import fs from "node:fs"
import { fileURLToPath } from "node:url"

import { Plugin } from "@opencode/plugin"

import { SUBAGENT_TOOLS, decideSubagentModel, validateRouting } from "../../tools/_agent_router.js"

const MAX_SESSIONS = 1000
// Hidden system agents run on their own small model inside a session; they must not hide the
// model of the agent that owns it.
const INTERNAL_AGENTS = new Set(["title", "summary", "compaction"])

export async function setupAgentRouter(ctx, options = {}) {
  const disabled = options.disabled === true || String(process.env.OPENCODE_AGENT_ROUTER ?? "").toLowerCase() === "off"
  if (disabled) return () => {}

  const routingPath = options.routingPath || process.env.OPENCODE_AGENT_ROUTING || fileURLToPath(new URL("./routing.json", import.meta.url))
  /** sessionId -> { agent, model } */
  const sessions = new Map()
  const disposers = []
  const keep = (dispose) => {
    if (typeof dispose === "function") disposers.push(dispose)
  }

  // Read on every subagent call (a few KB, a handful of calls per task); parse only when it changed.
  let cached = { text: null, routing: null }
  const routing = () => {
    try {
      const text = fs.readFileSync(routingPath, "utf8")
      if (text !== cached.text) cached = { text, routing: validateRouting(JSON.parse(text)) }
    } catch {
      cached = { text: null, routing: null }
    }
    return cached.routing
  }

  keep(ctx.session.hook("model.request", async (event) => {
    try {
      const id = event?.sessionID || event?.sessionId
      const agent = event?.agent
      if (!id || typeof agent !== "string" || INTERNAL_AGENTS.has(agent)) return
      if (sessions.size >= MAX_SESSIONS && !sessions.has(id)) sessions.delete(sessions.keys().next().value)
      sessions.set(id, { agent, model: event.model })
    } catch {
      /* fail open */
    }
  }))

  keep(ctx.tool.hook("execute.before", async (event) => {
    try {
      if (!SUBAGENT_TOOLS.has(event?.tool)) return
      const input = event.input
      if (!input || typeof input !== "object") return
      const session = sessions.get(event.sessionID || event.sessionId)
      const decision = decideSubagentModel(routing(), {
        callerAgent: typeof event.agent === "string" ? event.agent : session?.agent,
        callerModel: session?.model,
        targetAgent: input.agent ?? input.subagent_type,
        requestedModel: input.model,
      })
      if (decision) input.model = decision.model
    } catch {
      /* fail open */
    }
  }))

  return () => {
    for (const dispose of disposers.splice(0)) {
      try {
        dispose()
      } catch {
        /* ignore */
      }
    }
    sessions.clear()
  }
}

export default Plugin.define({
  id: "agent-router",
  setup: setupAgentRouter,
})
