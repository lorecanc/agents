// Pure routing logic of the manage-agents-router plugin, installed by manage-agents next to routing.json.
//
// When a primary agent of an archetype (declared by a pack: `archetype.callers`) delegates to a subagent, the
// subagent runs on the model configured for the provider (or exact model) the caller runs on right now:
//
//   1. a model the caller passed explicitly                          -> untouched
//   2. a pinned subagent (it has a fixed model)                      -> untouched, OpenCode uses it
//   3. routes["<provider>/<model>"], then routes["<provider>"]       -> that subagent's model
//   4. no route, or "inherit"                                        -> untouched: the caller's model
//
// routing.json is generated by `manage-agents reconcile` from the packs' routingDefaults and the user's routing
// configuration; it is never edited by hand.

export const ROUTING_VERSION = 2
export const SUBAGENT_TOOLS = new Set(["subagent", "task"])
const MODEL_RE = /^[^\s/#]+\/[^\s#]+(?:#[^\s#]+)?$/
const TRIGGER_RE = /^[^\s/#]+(?:\/[^\s#]+)?$/

export const isModelRef = (value) => typeof value === "string" && MODEL_RE.test(value)

/** { provider, model, full } from a hook payload ({providerID, id|modelID, variant}) or a "provider/model#variant" string. */
export function modelOf(ref) {
  if (typeof ref === "string") {
    if (!isModelRef(ref)) return null
    const [base] = ref.split("#")
    const slash = base.indexOf("/")
    return { provider: base.slice(0, slash), model: base.slice(slash + 1), full: ref }
  }
  if (!ref || typeof ref !== "object") return null
  const provider = ref.providerID ?? ref.provider
  const model = ref.id ?? ref.modelID ?? ref.model
  if (typeof provider !== "string" || !provider || typeof model !== "string" || !model) return null
  const variant = typeof ref.variant === "string" && ref.variant ? `#${ref.variant}` : ""
  return { provider, model, full: `${provider}/${model}${variant}` }
}

const isList = (value) => Array.isArray(value) && value.every(item => typeof item === "string" && item.length > 0)

/** Returns the routing or throws with the first problem. */
export function validateRouting(value) {
  const fail = (message) => { throw new Error(`routing.json: ${message}`) }
  if (!value || typeof value !== "object" || Array.isArray(value)) fail("not an object")
  if (value.version !== ROUTING_VERSION) fail(`unsupported version ${value.version}`)
  if (!value.archetypes || typeof value.archetypes !== "object" || Array.isArray(value.archetypes)) fail("missing archetypes")
  for (const [id, archetype] of Object.entries(value.archetypes)) {
    if (!isList(archetype?.callers)) fail(`${id}: callers must be a list of agent IDs`)
    if (!isList(archetype.pinned)) fail(`${id}: pinned must be a list of agent IDs`)
    if (!archetype.routes || typeof archetype.routes !== "object" || Array.isArray(archetype.routes)) fail(`${id}: missing routes`)
    for (const [trigger, agents] of Object.entries(archetype.routes)) {
      if (!TRIGGER_RE.test(trigger)) fail(`${id}: invalid trigger '${trigger}'`)
      if (!agents || typeof agents !== "object" || Array.isArray(agents)) fail(`${id}.${trigger}: not an object`)
      for (const [agent, model] of Object.entries(agents)) {
        if (model !== "inherit" && !isModelRef(model)) fail(`${id}.${trigger}.${agent}: '${model}' is not "inherit" or provider/model[#variant]`)
      }
    }
  }
  return value
}

/** The archetype whose callers include this agent, or null. */
export function archetypeOf(routing, agent) {
  if (typeof agent !== "string") return null
  return Object.values(routing?.archetypes ?? {}).find(archetype => archetype.callers.includes(agent)) ?? null
}

/** The routes for the caller's model: exact "provider/model" first, then "provider". */
export function routeFor(archetype, callerModel) {
  const model = modelOf(callerModel)
  if (!model) return null
  return archetype.routes[`${model.provider}/${model.model}`] ?? archetype.routes[model.provider] ?? null
}

/** { model } to inject into a subagent call, or null to leave the call as it is. */
export function decideSubagentModel(routing, { callerAgent, callerModel, targetAgent, requestedModel }) {
  if (!routing || (typeof requestedModel === "string" && requestedModel.trim())) return null
  const archetype = archetypeOf(routing, callerAgent)
  if (!archetype || typeof targetAgent !== "string" || !targetAgent || archetype.pinned.includes(targetAgent)) return null
  const model = routeFor(archetype, callerModel)?.[targetAgent]
  if (!isModelRef(model) || model === modelOf(callerModel)?.full) return null
  return { model }
}
