const ENGINE_OWNER = ":engine"
const ROUTER_DIR = "plugins/manage-agents-router"
const sha256 = (data: string | Buffer) => crypto.createHash("sha256").update(data).digest("hex")

/** runtime/ ships next to src/ and dist/, so it is found walking up from this module in both layouts. */
function engineRuntimeDir(): string {
  let dir = path.dirname(fileURLToPath(import.meta.url))
  for (;;) {
    const candidate = path.join(dir, "runtime", ...ROUTER_DIR.split("/"))
    if (fs.existsSync(path.join(candidate, "index.ts"))) return candidate
    const parent = path.dirname(dir)
    if (parent === dir) throw new Error("manage-agents runtime files are missing from the installation")
    dir = parent
  }
}

/** Computes what reconcile would do. Reads the target and the sources; never writes. */
export function planReconcile(target: string, lock: PackLock, registry: SourceRegistry, options: PlanOptions = {}): ReconcilePlan {
  const previous = readInstalled(target)
  const configFile = fs.existsSync(path.join(target, "opencode.jsonc")) ? "opencode.jsonc" : "opencode.json"
  const plan: ReconcilePlan = { target, packs: [], writes: [], deletes: [], released: [], conflicts: [], warnings: [], adopted: { files: [], config: [] }, configFile, configText: null, expected: {}, installed: previous }
  const { packs, problems } = loadLockedPacks(lock, registry, options.env)
  plan.packs = packs.map(pack => pack.name)
  plan.conflicts.push(...problems)
  if (problems.length) return plan
  const legacy = readLegacyResources(target)
  const env = options.env ?? process.env
  const overrideSettings = loadOverrideSettings(env)
  const overrides = new Map(packs.map(pack => [pack.name, effectiveOverrides(overrideSettings, target, pack.name)]))
  for (const [pack, value] of Object.entries({ ...overrideSettings.default, ...own(overrideSettings.targets, target) })) {
    if (!packs.some(loaded => loaded.name === pack)) plan.warnings.push(`overrides for pack "${pack}" have no effect: it is not installed in this target`)
    else for (const kind of ["agents", "commands"] as const) {
      const known = packs.find(loaded => loaded.name === pack)!.validation.ids[kind]
      for (const id of Object.keys(value[kind] ?? {})) if (!known.includes(id)) plan.warnings.push(`override ${pack}/${id}: the pack has no ${kind.slice(0, -1)} "${id}"`)
    }
  }

  const planned = new Map<string, PlannedWrite & { owner: string }>()
  const add = (write: PlannedWrite & { owner: string }) => {
    const existing = planned.get(fold(write.rel))
    if (existing) plan.conflicts.push(`${write.rel} is provided by both ${existing.owner === ENGINE_OWNER ? "manage-agents" : existing.owner} and ${write.owner === ENGINE_OWNER ? "manage-agents" : write.owner}`)
    else planned.set(fold(write.rel), write)
  }
  const ids = new Map<string, string>()
  const agentsByPack = new Map<string, Record<string, { mode?: string; model?: string }>>()
  for (const pack of packs) {
    for (const [kind, list] of Object.entries(pack.validation.ids)) {
      for (const id of list) {
        const key = `${kind}:${fold(id)}`
        const owner = ids.get(key)
        if (owner && owner !== pack.name) plan.conflicts.push(`${kind.replace(/s$/, "")} "${id}" is provided by both ${owner} and ${pack.name}`)
        else ids.set(key, pack.name)
      }
    }
    const packOverrides = overrides.get(pack.name)!
    const effective: Record<string, { mode?: string; model?: string }> = {}
    for (const agent of pack.validation.agents) {
      const patch = own(packOverrides.agents, agent.id)
      const value = (field: "mode" | "model") => {
        const patched = patch?.[field]
        return patched === null ? undefined : typeof patched === "string" ? patched : agent[field]
      }
      setOwn(effective, agent.id, { mode: value("mode"), model: value("model") })
    }
    agentsByPack.set(pack.name, effective)
    for (const rel of installableFiles(pack.validation)) {
      if (PACK_CONFIG_FILES.has(rel)) continue
      const dest = rel === "AGENTS.md" ? `instructions/${pack.name}.md` : rel
      const from = path.join(pack.dir, ...rel.split("/"))
      const mode = (fs.statSync(from).mode & 0o111) ? 0o755 : 0o644
      const [top, ...rest] = rel.split("/")
      const patch = (top === "agents" || top === "commands") && rel.endsWith(".md") ? own(packOverrides[top], rest.join("/").slice(0, -3)) : undefined
      if (!patch) { add({ rel: dest, from, hash: pack.fileHashes[rel], mode, kind: "create", owner: pack.name }); continue }
      const text = fs.readFileSync(from, "utf8")
      if (sha256(text) !== pack.fileHashes[rel]) { plan.conflicts.push(`${pack.name}: the source changed since the lock; run \`manage-agents update ${pack.name}\``); continue }
      const content = Buffer.from(patchFrontmatter(text, patch))
      add({ rel: dest, from, content, hash: sha256(content), mode, kind: "create", owner: pack.name })
    }
  }

  const routingSettings = loadRoutingSettings(env)
  for (const [pack, routes] of Object.entries({ ...routingSettings.default, ...own(routingSettings.targets, target) })) {
    const loaded = packs.find(candidate => candidate.name === pack)
    if (!loaded?.validation.manifest?.archetype) { plan.warnings.push(`routing for "${pack}" has no effect: no installed pack of that name declares an archetype`); continue }
    const callers = loaded.validation.manifest.archetype.callers
    const agents = agentsByPack.get(pack)!
    for (const agent of new Set(Object.values(routes).flatMap(Object.keys))) {
      if (!Object.hasOwn(agents, agent) || callers.includes(agent) || agents[agent].mode === "primary") plan.warnings.push(`routing for ${pack}: "${agent}" is not a subagent of the pack; ignored`)
    }
  }
  const routing = buildRuntimeRouting(packs.map(pack => ({ manifest: pack.validation.manifest!, agents: agentsByPack.get(pack.name)! })), routingSettings, target)
  if (routing) {
    const runtime = engineRuntimeDir()
    for (const file of ["index.ts", "router.js"]) {
      const from = path.join(runtime, file)
      add({ rel: `${ROUTER_DIR}/${file}`, from, hash: hashFile(from), mode: 0o644, kind: "create", owner: ENGINE_OWNER })
    }
    const content = Buffer.from(`${JSON.stringify(routing, null, 2)}\n`)
    add({ rel: `${ROUTER_DIR}/routing.json`, from: "", content, hash: sha256(content), mode: 0o644, kind: "create", owner: ENGINE_OWNER })
  }

  const files: InstalledState["files"] = {}
  const previousByFold = new Map(Object.entries(previous.files).map(([rel, owned]) => [fold(rel), owned]))
  for (const write of [...planned.values()].sort((a, b) => a.rel.localeCompare(b.rel))) {
    const { owner, ...entry } = write
    const current = currentHash(targetFile(target, write.rel))
    // Folded lookup: on a case-insensitive filesystem a renamed Foo.md -> foo.md is the same managed file.
    const owned = previousByFold.get(fold(write.rel))
    if (current === write.hash) {
      // An identical file the user put there stays theirs: uninstalling the pack must not delete it.
      if (owned || legacy.has(write.rel) || options.adopt) files[write.rel] = { hash: write.hash, owner }
      continue
    }
    if (current === "not-a-file") { plan.conflicts.push(`${write.rel}: a directory or special file is in the way`); continue }
    files[write.rel] = { hash: write.hash, owner }
    plan.expected[write.rel] = current
    if (current === null) plan.writes.push({ ...entry, kind: "create" })
    else if (owned && current === owned.hash) plan.writes.push({ ...entry, kind: "update" })
    else if ((!owned && legacy.has(write.rel)) || options.adopt) {
      plan.writes.push({ ...entry, kind: "adopt" })
      plan.adopted.files.push(write.rel)
    } else plan.conflicts.push(owned
      ? `${write.rel} was changed locally; rerun with --adopt to back it up and replace it`
      : `${write.rel} exists and is not managed by manage-agents; rerun with --adopt to back it up and replace it`)
  }
  for (const [rel, owned] of Object.entries(previous.files).sort(([a], [b]) => a.localeCompare(b))) {
    const successor = planned.get(fold(rel))
    if (successor && (successor.rel === rel || sameFile(targetFile(target, rel), targetFile(target, successor.rel)))) continue
    const current = currentHash(targetFile(target, rel))
    if (current === null) continue
    if (current === owned.hash) {
      plan.deletes.push(rel)
      plan.expected[rel] = current
    } else {
      plan.released.push(rel)
      plan.warnings.push(`${rel} was changed locally and no pack provides it any more: left in place, no longer managed`)
    }
  }

  const config = planConfig(target, configFile, packs, previous, legacy, options, plan, overrides, routing !== null)
  plan.installed = { installedVersion: 1, files, config }
  return plan
}

function planConfig(target: string, configFile: string, packs: LoadedPack[], previous: InstalledState, legacy: Set<string>, options: PlanOptions, plan: ReconcilePlan, overrides: Map<string, Required<PackOverrides>>, withRouter: boolean): Record<string, Contribution> {
  const full = path.join(target, configFile)
  if (fs.lstatSync(full, { throwIfNoEntry: false })?.isSymbolicLink()) {
    plan.conflicts.push(`${configFile} is a symlink; replace it with a regular file (or install into the directory it points to with --target)`)
    return previous.config
  }
  const text = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : null
  let current: Record<string, any>
  try {
    const parsed = text === null ? { $schema: SCHEMA } : parseJsonc(text)
    if (!isObject(parsed)) throw new Error("not a JSON object")
    current = parsed
  } catch (error) {
    plan.conflicts.push(`${configFile}: cannot be parsed (${(error as Error).message})`)
    return previous.config
  }

  const unmanaged: Record<string, any> = structuredClone(current)
  const changedLocally = new Set<string>()
  for (const contribution of Object.values(previous.config)) {
    for (const section of ARRAY_SECTIONS) {
      const list = unmanaged[section]
      if (!Array.isArray(list)) continue
      for (const entry of contribution[section] ?? []) {
        const index = list.findIndex(item => isDeepStrictEqual(item, entry))
        if (index !== -1) list.splice(index, 1)
      }
    }
    for (const [section, values] of Object.entries(contribution.objects ?? {})) {
      const object = getPath(unmanaged, section)
      if (!isObject(object)) continue
      for (const [key, value] of Object.entries(values)) {
        if (!Object.hasOwn(object, key)) continue
        if (isDeepStrictEqual(object[key], value)) delete object[key]
        else changedLocally.add(`${section}\0${key}`)
      }
    }
  }

  const legacyPlugins = new Set([...legacy].filter(rel => rel.startsWith("plugins/")).map(rel => `./plugins/${rel.split("/")[1]}`))
  const owners = new Map<string, { pack: string; value: unknown }>()
  const managedArrays: Record<string, unknown[]> = { plugins: [], skills: [], instructions: [] }
  const managedObjects: Record<string, Record<string, unknown>> = {}
  const contributions: Record<string, Contribution> = {}
  /** "managed": the pack owns the entry; "kept": an identical user entry stays the user's; "skip": duplicate or conflict. */
  const claim = (section: string, key: string, value: unknown, pack: string, existing: { present: boolean; value?: unknown; remove: () => void; legacy?: boolean }): "managed" | "kept" | "skip" => {
    const id = `${section}\0${key}`
    const owner = owners.get(id)
    if (owner) {
      if (!isDeepStrictEqual(owner.value, value)) plan.conflicts.push(`${configFile}: ${section} "${key}" is set differently by ${owner.pack} and ${pack}`)
      return "skip"
    }
    owners.set(id, { pack, value })
    if (!existing.present) return "managed"
    const identical = isDeepStrictEqual(existing.value, value)
    if (existing.legacy || options.adopt) {
      if (!identical) plan.adopted.config.push({ section, key, value: existing.value })
      existing.remove()
      return "managed"
    }
    if (identical) return "kept"
    plan.conflicts.push(changedLocally.has(id)
      ? `${configFile}: ${section} "${key}" was changed locally; rerun with --adopt to back it up and replace it`
      : `${configFile}: ${section} "${key}" exists and is not managed by manage-agents; rerun with --adopt to back it up and replace it`)
    return "skip"
  }

  const engine = { name: ENGINE_OWNER, contribution: { plugins: [`./${ROUTER_DIR}`], skills: [], instructions: [], objects: {} } as Contribution, implicitPlugins: new Set<string>() }
  const computed = [...packs.map(pack => ({ name: pack.name, ...packContribution(pack, target, overrides.get(pack.name)) })), ...(withRouter ? [engine] : [])]
  const explicitPlugins = new Set(computed.flatMap(({ contribution, implicitPlugins }) => contribution.plugins.map(pluginKey).filter(key => !implicitPlugins.has(key))))
  for (const { name, contribution, implicitPlugins } of computed) {
    const recorded: Contribution = { plugins: [], skills: [], instructions: [], objects: {} }
    contributions[name] = recorded
    for (const section of ARRAY_SECTIONS) {
      for (const entry of contribution[section]) {
        const key = arrayKey(section, entry)
        if (section === "plugins" && implicitPlugins.has(key) && explicitPlugins.has(key)) continue
        const list: unknown[] = Array.isArray(unmanaged[section]) ? unmanaged[section] : []
        const index = list.findIndex(item => arrayKey(section, item) === key)
        if (claim(section, key, entry, name, { present: index !== -1, value: list[index], remove: () => list.splice(index, 1), legacy: section === "plugins" && legacyPlugins.has(key) }) !== "managed") continue
        managedArrays[section].push(entry)
        ;(recorded[section] as unknown[]).push(entry)
      }
    }
    for (const [section, values] of Object.entries(contribution.objects)) {
      for (const [key, value] of Object.entries(values)) {
        const object = getPath(unmanaged, section)
        const present = isObject(object) && Object.hasOwn(object, key)
        if (claim(section, key, value, name, { present, value: present ? (object as Record<string, unknown>)[key] : undefined, remove: () => { delete (object as Record<string, unknown>)[key] } }) !== "managed") continue
        setOwn(managedObjects[section] ??= {}, key, value)
        setOwn(recorded.objects[section] ??= {}, key, value)
      }
    }
  }

  const next: Record<string, any> = structuredClone(unmanaged)
  for (const section of ARRAY_SECTIONS) {
    const merged = [...(Array.isArray(next[section]) ? next[section] : []), ...managedArrays[section]]
    if (merged.length) next[section] = merged
    else delete next[section]
  }
  for (const [section, values] of Object.entries(managedObjects)) {
    const object = ensurePath(next, section)
    for (const [key, value] of Object.entries(values)) setOwn(object, key, value)
  }

  const unchanged = text === null ? !packs.length : isDeepStrictEqual(next, current)
  if (!unchanged) {
    plan.configText = `${JSON.stringify(next, null, 2)}\n`
    plan.expected[configFile] = text === null ? null : hashFile(full)
    if (text !== null && !isPlainJson(text)) {
      plan.warnings.push(`${configFile} has comments or trailing commas, which are not preserved; the previous file is saved in the backup`)
      plan.adopted.files.push(configFile)
    }
  }
  return contributions
}

function isPlainJson(text: string): boolean {
  try {
    JSON.parse(text)
    return true
  } catch {
    return false
  }
}

const journalPath = (target: string) => statePath(target, "journal.json")
const transactionDir = (target: string, id: string) => path.join(targetStateDir(target), "txn", id)

function removeEmptyParents(target: string, rel: string) {
  let dir = path.dirname(targetFile(target, rel))
  while (dir !== target && dir.startsWith(`${target}${path.sep}`)) {
    try {
      fs.rmdirSync(dir)
    } catch {
      return
    }
    dir = path.dirname(dir)
  }
}

/** Undoes a transaction a crash left half-applied. Returns true when there was one. */
export function rollbackInterrupted(target: string): boolean {
  const journal = readJson(journalPath(target))
  if (journal === null) return false
  if (typeof journal.id !== "string" || !/^[\w-]+$/.test(journal.id) || !Array.isArray(journal.ops) || !journal.ops.every((op: any) => isSafeRel(op?.rel) && typeof op.existed === "boolean")) {
    throw new Error(`${journalPath(target)} is damaged; inspect it and ${transactionDir(target, "<id>")} before deleting them`)
  }
  const txn = transactionDir(target, journal.id)
  for (const op of [...journal.ops].reverse()) {
    const full = targetFile(target, op.rel)
    const previous = path.join(txn, "prev", ...op.rel.split("/"))
    if (fs.lstatSync(previous, { throwIfNoEntry: false })) {
      if (fs.lstatSync(full, { throwIfNoEntry: false })) fs.unlinkSync(full)
      fs.mkdirSync(path.dirname(full), { recursive: true })
      fs.renameSync(previous, full)
    } else if (!op.existed && typeof op.hash === "string" && currentHash(full) === op.hash) fs.unlinkSync(full)
  }
  fs.rmSync(journalPath(target), { force: true })
  fs.rmSync(txn, { recursive: true, force: true })
  return true
}

/**
 * Applies a plan as one transaction: everything is staged inside the target (same filesystem), a journal lists
 * every path, originals are moved aside, then staged files are renamed into place. A failure or a crash rolls back.
 */
export function applyPlan(plan: ReconcilePlan, state: { desired: DesiredState; lock: PackLock }): { backupId: string | null } {
  if (plan.conflicts.length) throw new Error(`refusing to apply a plan with conflicts: ${plan.conflicts[0]}`)
  const { target } = plan
  const id = `${new Date().toISOString().replace(/[:.]/g, "-")}-${crypto.randomBytes(4).toString("hex")}`
  const txn = transactionDir(target, id)
  const ops: Array<{ rel: string; staged: string | null; existed: boolean; hash?: string }> = []
  const stage = (rel: string, write: (staged: string) => void, mode: number | null, expectedHash?: string) => {
    const staged = path.join(txn, "new", ...rel.split("/"))
    fs.mkdirSync(path.dirname(staged), { recursive: true })
    write(staged)
    if (mode !== null) fs.chmodSync(staged, mode)
    const hash = currentHash(staged)!
    if (expectedHash && hash !== expectedHash) throw new Error(`${rel} changed in its source while installing; run the command again`)
    ops.push({ rel, staged, existed: fs.lstatSync(targetFile(target, rel), { throwIfNoEntry: false }) !== undefined, hash })
  }
  try {
    for (const write of plan.writes) {
      if (write.link !== undefined) stage(write.rel, staged => fs.symlinkSync(write.link!, staged), null)
      else if (write.content !== undefined) stage(write.rel, staged => fs.writeFileSync(staged, write.content!), write.mode, write.hash)
      else stage(write.rel, staged => fs.copyFileSync(write.from, staged), write.mode, write.hash)
    }
    if (plan.configText !== null) stage(plan.configFile, staged => fs.writeFileSync(staged, plan.configText!), 0o644)
    const json = (value: unknown) => (staged: string) => fs.writeFileSync(staged, `${JSON.stringify(value, null, 2)}\n`)
    stage(".manage-agents/installed.json", json(plan.installed), 0o644)
    stage(".manage-agents/lock.json", staged => fs.writeFileSync(staged, serializeLock(state.lock)), 0o644)
    stage(".manage-agents/desired.json", json({ desiredVersion: 1, roots: [...state.desired.roots].sort() }), 0o644)
  } catch (error) {
    fs.rmSync(txn, { recursive: true, force: true })
    throw error
  }
  for (const rel of plan.deletes) ops.push({ rel, staged: null, existed: true })
  // The target may have changed while the user was reading the confirmation prompt.
  const moved = ops.filter(op => op.rel in plan.expected && currentHash(targetFile(target, op.rel)) !== plan.expected[op.rel])
  if (moved.length) {
    fs.rmSync(txn, { recursive: true, force: true })
    throw new Error(`${moved[0].rel} changed while installing; nothing was written, run the command again`)
  }

  let backupId: string | null = null
  if (plan.adopted.files.length || plan.adopted.config.length) {
    backupId = id
    const dir = path.join(targetStateDir(target), "backups", id)
    for (const rel of plan.adopted.files) {
      const destination = path.join(dir, "files", ...rel.split("/"))
      fs.mkdirSync(path.dirname(destination), { recursive: true })
      const source = targetFile(target, rel)
      if (fs.lstatSync(source).isSymbolicLink()) fs.symlinkSync(fs.readlinkSync(source), destination)
      else fs.copyFileSync(source, destination)
    }
    atomicWriteRestrictedFile(path.join(dir, "backup.json"), Buffer.from(`${JSON.stringify({ id, created: new Date().toISOString(), configFile: plan.configFile, files: plan.adopted.files, config: plan.adopted.config }, null, 2)}\n`), 0o644)
  }

  atomicWriteRestrictedFile(journalPath(target), Buffer.from(JSON.stringify({ id, ops: ops.map(({ rel, existed, hash }) => ({ rel, existed, ...(hash ? { hash } : {}) })) })), 0o644)
  try {
    for (const op of ops) {
      const full = targetFile(target, op.rel)
      if (op.existed && fs.lstatSync(full, { throwIfNoEntry: false })) {
        const previous = path.join(txn, "prev", ...op.rel.split("/"))
        fs.mkdirSync(path.dirname(previous), { recursive: true })
        fs.renameSync(full, previous)
        // What was moved aside must be what the plan saw; otherwise the rollback below puts it back untouched.
        if (op.rel in plan.expected && currentHash(previous) !== plan.expected[op.rel]) throw new Error(`${op.rel} changed while installing; nothing was written, run the command again`)
      }
      if (op.staged) {
        fs.mkdirSync(path.dirname(full), { recursive: true })
        if (fs.lstatSync(full, { throwIfNoEntry: false })) throw new Error(`${op.rel} appeared while installing; nothing was written, run the command again`)
        fs.renameSync(op.staged, full)
      }
    }
  } catch (error) {
    rollbackInterrupted(target)
    throw error
  }
  fs.rmSync(journalPath(target), { force: true })
  fs.rmSync(txn, { recursive: true, force: true })
  for (const rel of plan.deletes) removeEmptyParents(target, rel)
  return { backupId }
}

function pidAlive(pid: number): boolean {
  try {
    process.kill(pid, 0)
    return true
  } catch (error) {
    return (error as NodeJS.ErrnoException).code === "EPERM"
  }
}

/** One install operation per target at a time (TUI and CLI included); a lock left by a dead process is reclaimed. */
export async function withTargetLock<T>(target: string, command: string, fn: () => Promise<T> | T): Promise<T> {
  const file = statePath(target, "install.lock")
  fs.mkdirSync(path.dirname(file), { recursive: true })
  const owner = JSON.stringify({ pid: process.pid, host: os.hostname(), command, started: new Date().toISOString() })
  for (let attempt = 0; ; attempt++) {
    try {
      fs.writeFileSync(file, owner, { flag: "wx" })
      break
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST" || attempt > 0) throw error
      let raw = ""
      let holder: any = null
      try {
        raw = fs.readFileSync(file, "utf8")
        holder = JSON.parse(raw)
      } catch {
        if (Date.now() - fs.statSync(file).mtimeMs < STALE_LOCK_GRACE_MS) throw new Error(`${target} is being installed by another process`)
      }
      if (holder && (holder.host !== os.hostname() || pidAlive(holder.pid))) {
        throw new Error(`${target} is locked by ${holder.command ?? "another command"} (pid ${holder.pid} on ${holder.host}, since ${holder.started}); if no manage-agents process is running, delete ${file}`)
      }
      // Move the stale lock aside atomically, then make sure it is the one judged stale: another process may have
      // reclaimed it and taken a fresh lock in between, and that lock must survive.
      const aside = `${file}.stale-${process.pid}-${crypto.randomBytes(4).toString("hex")}`
      try {
        fs.renameSync(file, aside)
      } catch {
        continue
      }
      if (fs.readFileSync(aside, "utf8") !== raw) {
        try {
          fs.linkSync(aside, file)
        } catch {
          /* a third process holds the lock now */
        }
        fs.rmSync(aside, { force: true })
        throw new Error(`${target} is being installed by another process`)
      }
      fs.rmSync(aside, { force: true })
    }
  }
  try {
    return await fn()
  } finally {
    try {
      if (JSON.parse(fs.readFileSync(file, "utf8")).pid === process.pid) fs.rmSync(file, { force: true })
    } catch {
      /* already gone */
    }
  }
}

export interface TargetChange {
  desired: DesiredState
  lock: PackLock
  problems: string[]
  warnings?: string[]
}

export interface ChangeOptions extends PlanOptions {
  dryRun?: boolean
  /** Asked when the change needs confirmation; resolving false aborts without writing. */
  confirm?: (reasons: string[]) => Promise<boolean>
}

export interface ChangeResult {
  status: "applied" | "unchanged" | "dry-run" | "failed" | "declined"
  recovered: boolean
  previousLock: PackLock | null
  change: TargetChange | null
  changes: LockChange[]
  confirmations: string[]
  plan: ReconcilePlan | null
  backupId: string | null
}

/** Shared skeleton of install, uninstall, update and reconcile: lock the target, compute, plan, confirm, apply. */
export async function changeTarget(target: string, command: string, registry: SourceRegistry, compute: (current: { desired: DesiredState; lock: PackLock | null }) => TargetChange, options: ChangeOptions = {}): Promise<ChangeResult> {
  return withTargetLock(target, command, async () => {
    const recovered = options.dryRun ? false : rollbackInterrupted(target)
    const previousLock = readLock(target)
    const result: ChangeResult = { status: "failed", recovered, previousLock, change: null, changes: [], confirmations: [], plan: null, backupId: null }
    const change = compute({ desired: readDesired(target), lock: previousLock })
    result.change = change
    if (change.problems.length) return result
    result.changes = diffLocks(previousLock, change.lock).changes
    result.confirmations = confirmationsNeeded(change.lock, previousLock)
    const plan = planReconcile(target, change.lock, registry, options)
    result.plan = plan
    if (plan.conflicts.length) return result
    const stateChanged = serializeLock(change.lock) !== (previousLock ? serializeLock(previousLock) : null) || !isDeepStrictEqual([...change.desired.roots].sort(), readDesired(target).roots)
    if (!plan.writes.length && !plan.deletes.length && plan.configText === null && !stateChanged && isDeepStrictEqual(plan.installed, readInstalled(target))) {
      result.status = "unchanged"
      return result
    }
    if (options.dryRun) {
      result.status = "dry-run"
      return result
    }
    if (result.confirmations.length && !(await (options.confirm ?? (async () => false))(result.confirmations))) {
      result.status = "declined"
      return result
    }
    result.backupId = applyPlan(plan, { desired: change.desired, lock: change.lock }).backupId
    result.status = "applied"
    return result
  })
}

/** Packs kept by the remaining roots (no re-resolution: versions stay as locked). */
export function pruneLock(lock: PackLock, roots: string[]): PackLock {
  const keep = new Set<string>()
  const visit = (name: string) => {
    if (keep.has(name) || !lock.packs[name]) return
    keep.add(name)
    for (const dependency of Object.keys(lock.packs[name].requires)) visit(dependency)
  }
  for (const root of roots) visit(parsePackRequest(root).name)
  return { ...lock, roots: [...roots].sort(), packs: Object.fromEntries(Object.entries(lock.packs).filter(([name]) => keep.has(name))) }
}

const EMPTY_LOCK: PackLock = { lockVersion: 1, contract: "1.0", roots: [], packs: {} }
type Compute = (current: { desired: DesiredState; lock: PackLock | null }) => TargetChange

function resolveForTarget(registry: SourceRegistry, roots: string[], pins: ResolveOptions["pins"], env: NodeJS.ProcessEnv): TargetChange {
  const { candidates, problems: discoveryProblems } = discoverAllPacks(registry, env)
  const resolution = resolvePacks(roots.map(parsePackRequest), candidates, { prefer: registry.prefer, pins, revisionOf: name => sourceRevision(findSource(registry, name), env) })
  return {
    desired: { desiredVersion: 1, roots },
    lock: resolution.problems.length ? EMPTY_LOCK : buildLock(resolution),
    problems: resolution.problems,
    warnings: [...discoveryProblems, ...resolution.warnings],
  }
}

const pinsFrom = (lock: PackLock | null, keep: (name: string, pack: LockedPack) => boolean) =>
  Object.fromEntries(Object.entries(lock?.packs ?? {}).filter(([name, pack]) => keep(name, pack)).map(([name, pack]) => [name, { source: pack.source, version: pack.version }]))

const isRoot = (desired: DesiredState, name: string) => desired.roots.some(root => parsePackRequest(root).name === name)

/** Adds root requests; every pack already locked keeps its source and version. */
export const installChange = (registry: SourceRegistry, requests: string[], env: NodeJS.ProcessEnv = process.env): Compute => ({ desired, lock }) => {
  const requested = new Set(requests.map(request => parsePackRequest(request).name))
  const roots = [...desired.roots.filter(root => !requested.has(parsePackRequest(root).name)), ...requests]
  return resolveForTarget(registry, roots, pinsFrom(lock, name => !requested.has(name)), env)
}

/** Removes root requests; dependencies still required by another root stay at their locked version. */
export const uninstallChange = (names: string[]): Compute => ({ desired, lock }) => {
  const problems = names.flatMap(name => {
    if (isRoot(desired, name)) return []
    const dependents = Object.entries(lock?.packs ?? {}).filter(([, pack]) => name in pack.requires).map(([dependent]) => dependent)
    return [dependents.length ? `${name} is installed as a dependency of ${dependents.join(", ")}; uninstall that instead` : `${name} is not installed`]
  })
  const roots = desired.roots.filter(root => !names.includes(parsePackRequest(root).name))
  return { desired: { desiredVersion: 1, roots }, lock: pruneLock(lock ?? EMPTY_LOCK, roots), problems }
}

/** Pulls the git sources of the named packs (all when none is named) and re-resolves; a git source moves as a whole. */
export const updateChange = (registry: SourceRegistry, names: string[], env: NodeJS.ProcessEnv = process.env, gitOptions: GitOptions = {}): Compute => ({ desired, lock }) => {
  if (!lock || !Object.keys(lock.packs).length) return { desired, lock: EMPTY_LOCK, problems: ["nothing is installed in this target; use `manage-agents install <pack>`"] }
  const selected = names.length ? names : Object.keys(lock.packs)
  const unknown = selected.filter(name => !lock.packs[name])
  if (unknown.length) return { desired, lock, problems: unknown.map(name => `${name} is not installed`) }
  const pulled = new Set<string>()
  for (const name of selected) {
    const source = findSource(registry, lock.packs[name].source)
    if (source.kind === "git" && !pulled.has(source.name)) {
      pullSource(source, env, gitOptions)
      pulled.add(source.name)
    }
  }
  return resolveForTarget(registry, desired.roots, pinsFrom(lock, (name, pack) => !selected.includes(name) && !pulled.has(pack.source)), env)
}

/** Rebuilds the target from the current desired state and lock. */
export const reconcileChange: Compute = ({ desired, lock }) =>
  lock && Object.keys(lock.packs).length ? { desired, lock, problems: [] } : { desired, lock: EMPTY_LOCK, problems: ["nothing is installed in this target; use `manage-agents install <pack>`"] }

export interface TargetStatus {
  target: string
  desired: DesiredState
  lock: PackLock | null
  interrupted: boolean
  drift: string[]
  plan: ReconcilePlan | null
}

/** Read-only report of everything that differs from the desired state and the lock. */
export function targetStatus(target: string, registry: SourceRegistry, env: NodeJS.ProcessEnv = process.env): TargetStatus {
  const desired = readDesired(target)
  const lock = readLock(target)
  const installed = readInstalled(target)
  const drift: string[] = []
  const interrupted = fs.existsSync(journalPath(target))
  if (interrupted) drift.push("an interrupted transaction is pending; the next install, update or reconcile rolls it back")
  const reportedSources = new Set<string>()
  for (const [name, locked] of Object.entries(lock?.packs ?? {})) {
    const source = registry.sources.find(candidate => candidate.name === locked.source)
    if (!source || source.kind !== "git" || reportedSources.has(source.name)) continue
    reportedSources.add(source.name)
    const fetched = lastFetchedRevision(source, env)
    const checkedOut = sourceRevision(source, env)
    if (checkedOut && checkedOut !== locked.revision) drift.push(`source ${source.name} is checked out at ${checkedOut.slice(0, 12)}, the lock has ${locked.revision?.slice(0, 12)}: run \`manage-agents update ${name}\``)
    else if (fetched && fetched !== locked.revision) drift.push(`source ${source.name} has new commits since the lock: run \`manage-agents update ${name}\``)
  }
  const reported = new Set<string>()
  for (const [rel, owned] of Object.entries(installed.files).sort(([a], [b]) => a.localeCompare(b))) {
    const current = currentHash(targetFile(target, rel))
    if (current !== null && current === owned.hash) continue
    reported.add(rel)
    drift.push(current === null ? `${rel} is missing: run \`manage-agents reconcile\`` : `${rel} was changed locally (\`manage-agents reconcile --adopt\` restores the pack version and keeps a backup)`)
  }
  const plan = lock ? planReconcile(target, lock, registry, { env }) : null
  if (plan) {
    drift.push(...plan.conflicts.filter(conflict => !reported.has(conflict.split(" ")[0])))
    const pending = plan.writes.filter(write => !reported.has(write.rel)).length + plan.deletes.length + (plan.configText !== null ? 1 : 0)
    if (!plan.conflicts.length && pending) drift.push(`reconcile would change ${pending} path(s)`)
  }
  if (!lock && desired.roots.length) drift.push("packs are requested but nothing is locked: run `manage-agents install`")
  return { target, desired, lock, interrupted, drift, plan }
}

/** Puts back what an --adopt replaced; the restored paths and entries become unmanaged again. */
export async function restoreBackup(target: string, backupId: string): Promise<{ files: string[]; config: AdoptedConfigEntry[] }> {
  if (!/^[\w-]+$/.test(backupId)) throw new Error(`invalid backup id "${backupId}"`)
  const dir = path.join(targetStateDir(target), "backups", backupId)
  const backup = readJson(path.join(dir, "backup.json"))
  if (!backup || !Array.isArray(backup.files) || !backup.files.every(isSafeRel) || !Array.isArray(backup.config)) throw new Error(`no usable backup "${backupId}" in ${path.dirname(dir)}`)
  return withTargetLock(target, "restore", () => {
    rollbackInterrupted(target)
    const installed = readInstalled(target)
    const configFile = typeof backup.configFile === "string" && PACK_CONFIG_FILES.has(backup.configFile) ? backup.configFile : "opencode.json"
    const configPath = path.join(target, configFile)
    if (fs.lstatSync(configPath, { throwIfNoEntry: false })?.isSymbolicLink()) throw new Error(`${configFile} is a symlink; restore does not replace it`)
    const fileBackups = (backup.files as string[]).filter(rel => rel !== configFile)
    const backupPath = (rel: string) => path.join(dir, "files", ...rel.split("/"))
    const plan: ReconcilePlan = { target, packs: [], writes: [], deletes: [], released: [], conflicts: [], warnings: [], adopted: { files: [], config: [] }, configFile, configText: null, expected: {}, installed }
    for (const rel of fileBackups) {
      delete installed.files[rel]
      const from = backupPath(rel)
      // A symlink the user had is recreated as a link, never followed: its target may be anywhere.
      if (fs.lstatSync(from).isSymbolicLink()) plan.writes.push({ rel, from, hash: "", mode: 0, kind: "update", link: fs.readlinkSync(from) })
      else plan.writes.push({ rel, from, hash: hashFile(from), mode: fs.statSync(from).mode & 0o777, kind: "update" })
    }
    if ((backup.files as string[]).includes(configFile)) {
      plan.configText = fs.readFileSync(path.join(dir, "files", configFile), "utf8")
      installed.config = {}
    } else if (backup.config.length) {
      const config = fs.existsSync(configPath) ? parseJsonc(fs.readFileSync(configPath, "utf8")) as Record<string, any> : { $schema: SCHEMA }
      for (const entry of backup.config as AdoptedConfigEntry[]) {
        if ((ARRAY_SECTIONS as readonly string[]).includes(entry.section)) {
          const list: unknown[] = Array.isArray(config[entry.section]) ? config[entry.section] : (config[entry.section] = [])
          const index = list.findIndex(item => arrayKey(entry.section, item) === entry.key)
          if (index !== -1) list.splice(index, 1, entry.value)
          else list.push(entry.value)
          for (const contribution of Object.values(installed.config)) (contribution as any)[entry.section] = ((contribution as any)[entry.section] ?? []).filter((item: unknown) => arrayKey(entry.section, item) !== entry.key)
        } else {
          setOwn(ensurePath(config, entry.section), entry.key, entry.value)
          for (const contribution of Object.values(installed.config)) delete contribution.objects?.[entry.section]?.[entry.key]
        }
      }
      plan.configText = `${JSON.stringify(config, null, 2)}\n`
    }
    const lock = readLock(target)
    applyPlan(plan, { desired: readDesired(target), lock: lock ?? { lockVersion: 1, contract: "1.0", roots: [], packs: {} } })
    return { files: fileBackups, config: backup.config }
  })
}
