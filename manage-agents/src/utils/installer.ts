export interface DesiredState {
  desiredVersion: 1
  roots: string[]
}

/** What one pack adds to opencode.json, already rewritten for the target. */
export interface Contribution {
  plugins: unknown[]
  skills: string[]
  instructions: string[]
  /** Section ("mcp.servers", "agents", "commands", "formatter", "lsp") -> key -> value. */
  objects: Record<string, Record<string, unknown>>
}

export interface InstalledState {
  installedVersion: 1
  files: Record<string, { hash: string; owner: string }>
  config: Record<string, Contribution>
}

export interface PlannedWrite {
  rel: string
  from: string
  hash: string
  mode: number
  kind: "create" | "update" | "adopt"
  /** Set when restoring a symlink the user had: the link text is recreated, never followed. */
  link?: string
  /** Generated bytes (overridden frontmatter, routing.json) instead of a copy of `from`. */
  content?: Buffer
}

export interface AdoptedConfigEntry {
  section: string
  key: string
  value: unknown
}

export interface ReconcilePlan {
  target: string
  packs: string[]
  writes: PlannedWrite[]
  deletes: string[]
  /** Owned files the user changed that no pack provides any more: left in place, no longer managed. */
  released: string[]
  conflicts: string[]
  warnings: string[]
  /** Unmanaged or locally changed content replaced by this plan; backed up before the write. */
  adopted: { files: string[]; config: AdoptedConfigEntry[] }
  configFile: string
  /** Next opencode.json text, or null when the config does not change. */
  configText: string | null
  /** Hash (or null for absent) of every target path the plan touches, as seen when planning; apply aborts on any difference. */
  expected: Record<string, string | null>
  installed: InstalledState
}

export interface LoadedPack {
  name: string
  locked: LockedPack
  dir: string
  validation: PackValidation
  /** Hash of each installable file, verified against the lock; staging checks the copied bytes against it. */
  fileHashes: Record<string, string>
  /** The pack's opencode.json(c) as verified against the lock, or null. */
  configText: string | null
}

