/** Paths read back from state files are trusted only when they stay inside the target. */
function isSafeRel(rel: unknown): rel is string {
  return typeof rel === "string" && rel.length > 0 && !rel.includes("\\") && !rel.includes("\0") && !path.posix.isAbsolute(rel) && !path.win32.isAbsolute(rel)
    && rel.split("/").every(part => part !== "" && part !== "." && part !== "..")
}

function readJson(file: string): any {
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : null
}

function getPath(object: Record<string, any>, dotted: string): unknown {
  return dotted.split(".").reduce<any>((value, key) => isObject(value) ? value[key] : undefined, object)
}

function ensurePath(object: Record<string, any>, dotted: string): Record<string, any> {
  let current = object
  for (const key of dotted.split(".")) {
    if (!isObject(current[key])) current[key] = {}
    current = current[key]
  }
  return current
}

export function readDesired(target: string): DesiredState {
  const file = statePath(target, "desired.json")
  const raw = readJson(file)
  if (raw === null) return { desiredVersion: 1, roots: [] }
  if (raw?.desiredVersion !== 1 || !Array.isArray(raw.roots)) throw new Error(`${file}: unsupported desired state`)
  for (const root of raw.roots) parsePackRequest(String(root))
  return { desiredVersion: 1, roots: raw.roots }
}

export function readInstalled(target: string): InstalledState {
  const file = statePath(target, "installed.json")
  const raw = readJson(file)
  if (raw === null) return { installedVersion: 1, files: {}, config: {} }
  const filesValid = isObject(raw?.files) && Object.entries(raw.files).every(([rel, owned]: [string, any]) =>
    isSafeRel(rel) && typeof owned?.hash === "string" && typeof owned.owner === "string")
  if (raw?.installedVersion !== 1 || !filesValid || !isObject(raw.config)) throw new Error(`${file}: unsupported or damaged installed state`)
  return raw
}

/** Paths installed by the legacy `manage-agents export`; the pack installer may replace them without --adopt. */
function readLegacyResources(target: string): Set<string> {
  try {
    const raw = readJson(path.join(target, ".resource-export-manifest.json"))
    return new Set(raw?.owner === "manage-agents" && Array.isArray(raw.resources) ? raw.resources.filter(isSafeRel) : [])
  } catch {
    return new Set()
  }
}

/** Two spellings of one path on a case-insensitive filesystem resolve to the same inode. */
function sameFile(a: string, b: string): boolean {
  const first = fs.lstatSync(a, { throwIfNoEntry: false })
  const second = fs.lstatSync(b, { throwIfNoEntry: false })
  return !!first && !!second && first.dev === second.dev && first.ino === second.ino
}

function currentHash(full: string): string | null {
  const stat = fs.lstatSync(full, { throwIfNoEntry: false })
  if (!stat) return null
  if (stat.isSymbolicLink()) return `symlink:${fs.readlinkSync(full)}`
  if (!stat.isFile()) return "not-a-file"
  return hashFile(full)
}

/** Locates every locked pack (git packs at their locked revision) and checks it still matches the lock. */
export function loadLockedPacks(lock: PackLock, registry: SourceRegistry, env: NodeJS.ProcessEnv = process.env): { packs: LoadedPack[]; problems: string[] } {
  const packs: LoadedPack[] = []
  const problems: string[] = []
  const names = orderByRequires(Object.keys(lock.packs), name => Object.keys(lock.packs[name].requires))
  for (const name of names) {
    const locked = lock.packs[name]
    const source = registry.sources.find(candidate => candidate.name === locked.source)
    if (!source) { problems.push(`${name}: source "${locked.source}" is not registered`); continue }
    if (source.kind !== locked.sourceKind) { problems.push(`${name}: source "${locked.source}" changed kind since the lock`); continue }
    let base: string
    try {
      base = source.kind === "local" ? source.path : revisionSnapshot(source, locked.revision ?? "", env)
    } catch (error) {
      problems.push(`${name}: ${(error as Error).message}`)
      continue
    }
    const dir = path.resolve(base, ...locked.path.split("/"))
    const inside = path.relative(base, dir)
    if (inside.startsWith("..") || path.isAbsolute(inside) || !fs.existsSync(dir)) { problems.push(`${name}: ${locked.path} is missing from source "${locked.source}"`); continue }
    const validation = validatePack(dir, { sourceKind: source.kind })
    const changed = `${name}: the source changed since the lock; run \`manage-agents update ${name}\``
    if (hasErrors(validation)) { problems.push(`${name}: the pack no longer satisfies the contract; run \`manage-agents pack validate ${dir}\``); continue }
    if (hashFile(path.join(dir, "opencode-pack.json")) !== locked.manifestHash) { problems.push(changed); continue }
    const configRel = validation.files.find(file => PACK_CONFIG_FILES.has(file))
    const configText = configRel ? fs.readFileSync(path.join(dir, configRel), "utf8") : null
    const { fileHashes, contentHash, executableHash } = packContent(validation)
    // The config is read once and checked against the hash that went into the lock, so it cannot change unseen.
    const configMatches = !configRel || crypto.createHash("sha256").update(configText!).digest("hex") === fileHashes[configRel]
    if (contentHash !== locked.contentHash || executableHash !== locked.executableHash || !configMatches) { problems.push(changed); continue }
    packs.push({ name, locked, dir, validation, fileHashes, configText })
  }
  return { packs, problems }
}

const normalizePluginSpec = (spec: string) => {
  const local = spec.replace(/^file:(?:\/\/)?/, "")
  return local.startsWith("./") || local.startsWith("../") ? `./${path.posix.normalize(local).replace(/\/$/, "")}` : spec
}
const pluginKey = (entry: unknown) => normalizePluginSpec(typeof entry === "string" ? entry : isObject(entry) && typeof entry.package === "string" ? entry.package : JSON.stringify(entry))
const arrayKey = (section: string, entry: unknown) => section === "plugins" ? pluginKey(entry) : String(entry)

/**
 * The pack's opencode.json(c) and AGENTS.md as target config entries. Every shipped plugin is registered; the
 * plugins registered only implicitly are listed in `implicitPlugins`, so a dependent pack can configure them.
 */
export function packContribution(pack: LoadedPack, target: string, overrides: Required<PackOverrides> = { agents: {}, commands: {} }): { contribution: Contribution; implicitPlugins: Set<string> } {
  const contribution: Contribution = { plugins: [], skills: [], instructions: [], objects: {} }
  const config = pack.configText !== null ? parseJsonc(pack.configText) as Record<string, any> : {}
  const local = new Map<string, unknown>()
  const packages: unknown[] = []
  const implicitPlugins = new Set<string>()
  for (const entry of Array.isArray(config.plugins) ? config.plugins : []) {
    const key = pluginKey(entry)
    if (!key.startsWith("./plugins/")) { packages.push(entry); continue }
    local.set(key, typeof entry === "string" ? key : { ...entry, package: key })
  }
  for (const id of pack.validation.ids.plugins) {
    if (local.has(`./plugins/${id}`)) continue
    local.set(`./plugins/${id}`, `./plugins/${id}`)
    implicitPlugins.add(`./plugins/${id}`)
  }
  contribution.plugins = [...[...local.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, entry]) => entry), ...packages]
  const toTarget = (item: string) => /^https?:\/\//.test(item) ? item : path.join(target, ...item.split("/"))
  contribution.skills = (Array.isArray(config.skills) ? config.skills : []).map(toTarget)
  contribution.instructions = (Array.isArray(config.instructions) ? config.instructions : []).map(toTarget)
  if (pack.validation.files.includes("AGENTS.md")) contribution.instructions.push(path.join(target, "instructions", `${pack.name}.md`))
  for (const section of OBJECT_SECTIONS) {
    const value = getPath(config, section)
    if (isObject(value) && Object.keys(value).length) contribution.objects[section] = { ...value }
  }
  for (const kind of ["agents", "commands"] as const) {
    const section = contribution.objects[kind]
    for (const [id, patch] of Object.entries(overrides[kind])) {
      if (!section || !Object.hasOwn(section, id) || !isObject(section[id])) continue
      const patched: Record<string, unknown> = { ...section[id] }
      for (const [field, value] of Object.entries(patch)) {
        if (value === null) delete patched[field]
        else setOwn(patched, field, value)
      }
      setOwn(section, id, patched)
    }
  }
  return { contribution, implicitPlugins }
}

